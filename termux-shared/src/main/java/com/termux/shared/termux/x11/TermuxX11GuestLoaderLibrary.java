package com.termux.shared.termux.x11;

import android.content.Context;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;

import com.termux.shared.errors.Errno;
import com.termux.shared.errors.Error;
import com.termux.shared.file.FileUtils;
import com.termux.shared.logger.Logger;
import com.termux.shared.termux.TermuxConstants;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.util.Map;

/**
 * Guest-side loader for the embedded termux-x11 companion (spec 014, enmienda A),
 * replicating the upstream deb mechanism without a deb or a separate loader APK:
 * the app injects the host APK path into the proot guest environment
 * ({@code TERMUX_X11_APK}) and keeps an idempotent wrapper script in the Debian
 * rootfs that starts the companion with that classpath:
 *
 * <pre>
 *   CLASSPATH=${TERMUX_X11_APK:?} /system/bin/app_process / \
 *       --nice-name=termux-x11 com.termux.x11.CmdEntryPoint "$@"
 * </pre>
 *
 * Pure helpers ({@link #applyApkPathEnv}, {@link #buildWrapperScript},
 * {@link #contentMatches}) are unit-testable without Android.
 */
public final class TermuxX11GuestLoaderLibrary {

    private static final String LOG_TAG = "TermuxX11GuestLoaderLibrary";

    /** Guest environment variable holding the host APK path to use as companion classpath. */
    public static final String ENV_X11_APK = "TERMUX_X11_APK"; // Default: "TERMUX_X11_APK"

    private TermuxX11GuestLoaderLibrary() {
    }

    /**
     * Apply the {@link #ENV_X11_APK} entry to an environment map (pure).
     *
     * @param env environment map to modify in place; must be mutable, must not be {@code null}
     * @param apkPath host APK path ({@code applicationInfo.sourceDir}); {@code null}/blank skips
     * @throws IllegalArgumentException when {@code env} is {@code null}
     */
    public static void applyApkPathEnv(@NonNull Map<String, String> env, @Nullable String apkPath) {
        if (env == null)
            throw new IllegalArgumentException("env must not be null");
        if (apkPath == null || apkPath.trim().isEmpty())
            return;
        env.put(ENV_X11_APK, apkPath.trim());
    }

    /**
     * Build the guest wrapper script text (pure, deterministic). Ends with a
     * trailing newline so the file is well-formed POSIX text. The
     * {@code ${TERMUX_X11_APK:?}} guard makes bash abort with the variable name
     * in its own error message when the session env was not injected.
     *
     * @return full wrapper script
     */
    public static String buildWrapperScript() {
        String processName = TermuxConstants.TERMUX_X11.X11_COMPANION_PROCESS_NAME;
        return "#!/bin/bash\n"
            + "# termux-x11 companion launcher (generated by the Terminal app, spec 014).\n"
            + "# Regenerated on app start; env TERMUX_X11_APK is injected per proot session.\n"
            + "export CLASSPATH=${" + ENV_X11_APK + ":?}\n"
            + "exec /system/bin/app_process / --nice-name=" + processName
            + " " + "com.termux.x11.CmdEntryPoint \"$@\"\n";
    }

    /**
     * Whether an existing file content should be replaced by {@code desired}
     * (pure idempotence key). Tolerates a missing or extra trailing newline so
     * editor round-trips do not force rewrites.
     *
     * @param existing current content; {@code null} means the file is absent
     * @param desired desired content
     * @return {@code true} when the script must be (re)written
     */
    public static boolean contentMatches(@Nullable String existing, @Nullable String desired) {
        if (existing == null || desired == null)
            return false;
        return stripTrailingNewline(existing).equals(stripTrailingNewline(desired));
    }

    private static String stripTrailingNewline(@Nullable String s) {
        if (s == null) return "";
        String out = s;
        while (out.endsWith("\n") || out.endsWith("\r"))
            out = out.substring(0, out.length() - 1);
        return out;
    }

    /**
     * Ensure the guest wrapper script exists at
     * {@link TermuxConstants.TERMUX_X11#X11_GUEST_WRAPPER_HOST_PATH} with the
     * current content and the executable bit set. Cheap no-op when the content
     * already matches; safe to call on every app start (idempotent).
     *
     * @param context any app context, must not be {@code null}
     * @return {@code null} on success (including no-op), otherwise the {@link Error}
     */
    @Nullable
    public static Error ensureWrapperScript(@NonNull Context context) {
        if (context == null)
            return Errno.ERRNO_FAILED.getError("context must not be null", "ensureWrapperScript");

        String hostPath = TermuxConstants.TERMUX_X11.X11_GUEST_WRAPPER_HOST_PATH;
        String desired = buildWrapperScript();

        // Fast path: script already current.
        if (new File(hostPath).isFile()) {
            StringBuilder existing = new StringBuilder();
            Error readError = FileUtils.readTextFromFile(null, hostPath,
                StandardCharsets.UTF_8, existing, true);
            if (readError == null && contentMatches(existing.toString(), desired))
                return null;
        }

        // `usr/bin` normally comes with the extracted rootfs, but create it when absent.
        File parent = new File(hostPath).getParentFile();
        if (parent != null && !parent.isDirectory() && !parent.mkdirs()) {
            Error mkdirError = Errno.ERRNO_FAILED.getError("Failed to create the termux-x11 wrapper parent directory \"" + parent.getAbsolutePath() + "\"");
            Logger.logErrorExtended(LOG_TAG, "Failed\n" + mkdirError);
            return mkdirError;
        }

        Error writeError = FileUtils.writeTextToFile("termux-x11 wrapper", hostPath,
            StandardCharsets.UTF_8, desired, false);
        if (writeError != null) {
            Logger.logErrorExtended(LOG_TAG, "Failed to write guest wrapper\n" + writeError);
            return writeError;
        }

        // The guest runs the script directly; the exec bit is required.
        FileUtils.setMissingFilePermissions("termux-x11 wrapper", hostPath, "rwx");
        if (!new File(hostPath).canExecute()) {
            Error error = Errno.ERRNO_FAILED.getError("Failed to set the execute bit on the termux-x11 guest wrapper at path \"" + hostPath + "\"");
            Logger.logErrorExtended(LOG_TAG, "Failed\n" + error);
            return error;
        }

        Logger.logDebug(LOG_TAG, "termux-x11 guest wrapper ensured at \"" + hostPath + "\"");
        return null;
    }
}
